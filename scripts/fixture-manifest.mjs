#!/usr/bin/env node
// Builds tests/fixtures/MANIFEST.json (filename, description, source, license, attribution,
// SHA-256, dimensions, coverage) from the procedural index and external SOURCES.json.
// `--check` verifies the committed manifest against the files instead of writing it.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const dir = resolve(import.meta.dirname, "../tests/fixtures");
const read = (p) => JSON.parse(readFileSync(join(dir, p), "utf8"));

function dimensions(buf) {
  if (buf.readUInt32BE(0) === 0x89504e47) return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  for (let i = 2; i < buf.length;) {
    const marker = buf[i + 1];
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker))
      return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
    i += 2 + buf.readUInt16BE(i + 2);
  }
  throw new Error("unknown image");
}

const procedural = read("procedural/index.json").map((f) => ({
  ...f,
  source:
    "Procedurally generated by crates/vector-engine/examples/gen_fixtures.rs (tests/common/fixtures.rs)",
  license: "Same as the repository (proposed MIT); generated, no third-party content",
  attribution: "None",
}));
const entries = [...procedural, ...read("external/SOURCES.json")].map((f) => {
  const buf = readFileSync(join(dir, f.file));
  const [width, height] = dimensions(buf);
  return {
    ...f,
    bytes: buf.length,
    width,
    height,
    sha256: createHash("sha256").update(buf).digest("hex"),
  };
});
const json = JSON.stringify(entries, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(join(dir, "MANIFEST.json"), "utf8") !== json) {
    console.error("tests/fixtures/MANIFEST.json is out of date or a fixture changed");
    process.exit(1);
  }
  console.log(`fixture manifest verified (${entries.length} files)`);
} else {
  writeFileSync(join(dir, "MANIFEST.json"), json);
  console.log(
    `wrote MANIFEST.json (${entries.length} files, ${entries.reduce((s, e) => s + e.bytes, 0)} bytes)`,
  );
}
