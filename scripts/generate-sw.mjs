#!/usr/bin/env node
// Writes dist/sw.js: a versioned service worker that precaches every file of this build so a
// cancelled (terminated) Web Worker can be recreated while offline. Browsers fetch the
// `new Worker(url)` script and the .wasm over the network unless a service worker answers;
// WebKit does not fall back to the HTTP cache offline (P0-R-G2).
//
// Versioning: VERSION is a hash of every precached file, and all asset names are
// content-hashed by Vite, so a page, its worker and its .wasm always come from one build.
// A new deployment installs a new cache and waits (no skipWaiting) until pages controlled
// by the old version are closed; activation then deletes older vectra-* caches.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const dist = resolve(process.argv[2] ?? resolve(import.meta.dirname, "../dist"));
const EXCLUDE = new Set(["_headers", "_redirects", "sw.js"]);
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else {
      const rel = relative(dist, p).split("\\").join("/");
      if (!EXCLUDE.has(rel)) files.push(rel);
    }
  }
};
walk(dist);

const hash = createHash("sha256");
for (const f of files)
  hash
    .update(f)
    .update("\0")
    .update(readFileSync(join(dist, f)));
const version = hash.digest("hex").slice(0, 16);
const precache = files.map((f) => `./${f}`);

const sw = `// Generated by scripts/generate-sw.mjs for this build. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "vectra-" + VERSION;
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE.map((url) => new Request(url, { cache: "reload" })))),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith("vectra-") && key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "vectra-sw-version") event.source?.postMessage({ type: "vectra-sw-version", version: VERSION });
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    // Network first so deployments are picked up; cached shell when offline.
    event.respondWith(
      fetch(request).catch(async () => (await caches.match("./index.html", { cacheName: CACHE })) || Response.error()),
    );
    return;
  }
  // Hashed build assets: cache first, network as fallback (e.g. a file evicted from the cache).
  event.respondWith(caches.match(request, { cacheName: CACHE }).then((hit) => hit || fetch(request)));
});
`;
writeFileSync(join(dist, "sw.js"), sw);
console.log(`dist/sw.js: version ${version}, ${precache.length} precached files`);
